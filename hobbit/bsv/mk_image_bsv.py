#!/usr/bin/env python3
"""Turn a fixed-format Hobbit image into a Bluespec word table.

Usage: python3 mk_image_bsv.py IMAGE MODULE > Generated.bsv

IMAGE is the project contract: one 32-bit word per line, exactly eight
lowercase hex digits, words in increasing address order from 0.  MODULE is
the emitted BSV package name; the package exports imageLength() and
imageWord(i), the latter with a zero default so reads past the image are
defined.

The generator is deliberately strict: a malformed line is an error with
file:line, because a silent short image would make the model and the
reference trace disagree for the wrong reason.
"""

import re
import sys

WORD_RE = re.compile(r"^[0-9a-fA-F]{8}$")
MODULE_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def read_image(path):
    words = []
    with open(path, "r", encoding="utf-8") as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.strip()
            if not line:
                continue
            if not WORD_RE.match(line):
                sys.exit("%s:%d: error: expected eight hex digits" % (path, lineno))
            words.append(int(line, 16))
    if not words:
        sys.exit("%s: error: empty image" % path)
    return words


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: mk_image_bsv.py IMAGE MODULE > Generated.bsv\n")
        return 2
    image, module = argv[1], argv[2]
    if not MODULE_RE.match(module):
        sys.exit("%s: error: not a BSV identifier" % module)
    words = read_image(image)

    out = []
    out.append("// Generated by mk_image_bsv.py from %s.  Do not edit." % image)
    out.append("package %s;" % module)
    out.append("")
    out.append("import HobbitTypes::*;")
    out.append("")
    out.append("function Bit#(32) imageLength();")
    out.append("  return 32'd%d;" % len(words))
    out.append("endfunction")
    out.append("")
    out.append("function Word imageWord(Bit#(16) i);")
    out.append("  case (i)")
    for i, w in enumerate(words):
        out.append("    16'd%d: return 32'h%08x;" % (i, w))
    out.append("    default: return 32'h00000000;")
    out.append("  endcase")
    out.append("endfunction")
    out.append("")
    out.append("endpackage")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
