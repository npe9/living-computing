class Var:
    __slots__ = ('ref', 'name')
    n = 0

    def __init__(self):
        self.ref = None
        Var.n += 1
        self.name = '_G%d' % Var.n

    def __repr__(self):
        return self.name if self.ref is None else repr(deref(self))


class Atom:
    table = {}
    __slots__ = ('name',)

    def __new__(cls, name):
        a = Atom.table.get(name)
        if a is None:
            a = object.__new__(cls)
            a.name = name
            Atom.table[name] = a
        return a

    def __repr__(self):
        return self.name


NIL = Atom('[]')


class Functor:
    """The key `pmi ce` (switch_on_vector, step 3g) puts in its register
    for a vector {Name, ...} of N elements, and the key cell a `cc` or a
    hash table after it holds: tag 01 with the low byte N, printed by
    ptfread as the selector Name/N.  N is the vector's length, element 0
    included (MEASURED with source: receiver.esp:669-680 `init(pe_view,PE,
    Wid)`, `init(htree_view)`, `init(htree_view,{Id,Nid},Depth,Wid)` are
    the three keys init/4, init/2, init/5 of receiver send/3's cd04
    table @126).  The representation is OURS; interned, so `is` compares."""
    table = {}
    __slots__ = ('name', 'n')

    def __new__(cls, name, n):
        f = Functor.table.get((name, n))
        if f is None:
            f = object.__new__(cls)
            f.name, f.n = name, n
            Functor.table[(name, n)] = f
        return f

    def __repr__(self):
        return '%s/%d' % (self.name, self.n)


class Cons:
    __slots__ = ('args',)

    def __init__(self, car, cdr):
        self.args = [car, cdr]

    def __repr__(self):
        out, t = [], self
        while isinstance(t, Cons):
            out.append(repr(deref(t.args[0])))
            t = deref(t.args[1])
        return '[%s%s]' % (','.join(out), '' if t is NIL else '|%r' % (t,))


class Vec:
    __slots__ = ('args', 'heap')

    def __init__(self, args, heap=False):
        self.args, self.heap = list(args), heap

    def __repr__(self):
        return '{%s}' % ','.join(repr(deref(a)) for a in self.args)


class Str:
    """A string.  TEXT is the elements as ptfdump.ch decodes their 16-bit
    JIS codes; TYPE the element type (16: OURS for every string here).
    Strings are mutable (set_string_element/3)."""
    __slots__ = ('text', 'type')

    def __init__(self, text, type=16):
        self.text = text
        self.type = type

    def codes(self):
        """The elements as codes: the inverse of ptfdump.ch (a `<xxxx>`
        token is one code; OURS where a literal '<' could be read so)."""
        out, t, i = [], self.text, 0
        while i < len(t):
            c = t[i]
            if c == "<" and t[i + 5:i + 6] == ">" and all(
                    x in '0123456789abcdef' for x in t[i + 1:i + 5]):
                out.append(int(t[i + 1:i + 5], 16))
                i += 6
                continue
            if c in _PUNCT_CODE:
                out.append(0x2100 | _PUNCT_CODE[c])
            elif '!' <= c <= '~':
                out.append(0x2300 | ord(c))
            else:
                raise Refusal('built-in', 'string element %r has no code here' % c)
            i += 1
        return out

    def set_codes(self, codes):
        self.text = ''.join(P.ch(x) for x in codes)

    # Python equality compares contents, for tests and tables only.  KL0's
    # unification and `==` do NOT use it: on the PSI two strings unify only
    # when they are the same stored string (see Machine.unify).
    def __eq__(self, o):
        return isinstance(o, Str) and o.text == self.text

    def __hash__(self):
        return hash(self.text)

    def __repr__(self):
        return 'string#%r' % self.text


_PUNCT_CODE = {v: k for k, v in P.PUNCT.items()}


class ClassRef:
    __slots__ = ('cid',)

    def __init__(self, cid):
        self.cid = cid

    def __eq__(self, o):
        return isinstance(o, ClassRef) and o.cid == self.cid

    def __hash__(self):
        return hash(self.cid)

    def __repr__(self):
        return '#' + self.cid


class Instance:
    __slots__ = ('cid', 'slots')

    def __init__(self, cid, slots):
        self.cid, self.slots = cid, slots

    def __repr__(self):
        return '<%s>' % self.cid


class Barrier:
    """The cut barrier a predicate finds in register A_arity on entry
    (kappa##kappaDBC_interface pic/1: `20 01 00` saves A1, `dd 01 01`
    cuts to it, `a2 01 00` reloads it after a call, `de 01 01` cuts again).
    B is the choice-point stack height: OURS representation."""
    __slots__ = ('b',)

    def __init__(self, b):
        self.b = b

    def __repr__(self):
        return '<barrier %d>' % self.b


def deref(t):
    while isinstance(t, Var) and t.ref is not None:
        t = t.ref
    return t


def is_atomic(t):
    return isinstance(t, (Atom, int, Str, ClassRef, Instance))


