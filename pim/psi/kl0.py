def load_table(path=TSV):
    with open(path) as f:
        return [r for r in csv.DictReader(f, delimiter='\t')]


class Frame:
    __slots__ = ('y', 'prev', 'cont', 'b0')

    def __init__(self, n, prev, cont, b0):
        self.y = [Var() for _ in range(n)]
        self.prev, self.cont, self.b0 = prev, cont, b0


class Choice:
    __slots__ = ('alt', 'x', 'env', 'cont', 'b0', 'trail', 'cur')

    def __init__(self, alt, m):
        self.alt = alt
        self.x = dict(m.x)
        self.env, self.cont, self.b0 = m.env, m.cont, m.b0
        self.trail = len(m.trail)
        self.cur = None


class Syn:
    """Synthetic code for a combined method (TM-388 §3.4), OURS: a list of
    pseudo-instructions run by the same machine."""

    def __init__(self, label, ops):
        self.id, self.ops = label, ops


class Machine:
    def __init__(self, lib, table=None, max_steps=200000):
        self.lib = lib
        self.rows = table if table is not None else load_table()
        self.codes = {}
        self.class_slots = {}
        self.max_steps = max_steps
        self.handlers = {}
        for r in self.rows:
            if not r['witness'].strip():
                continue
            fn = getattr(self, 'op_' + r['mnemonic'], None)
            if fn is None:
                raise ValueError('table row without an implementation: %r' % r['mnemonic'])
            self.handlers[(r['class'], r['opcode'])] = fn
        self.trace = None
        # census recipes (step 3f, OURS): a send whose (name, arity) is in
        # this set raises CreatorStopped instead of being dispatched
        self.stop_before = None
        self.sender = None

    # -- code --------------------------------------------------------------
    def code(self, cid):
        c = self.codes.get(cid)
        if c is None:
            t = self.lib.templates[cid]
            c = self.codes[cid] = Code(self.lib, t)
        return c

    # -- unification -------------------------------------------------------
    def bind(self, v, t):
        v.ref = t
        self.trail.append(v)

    def unify(self, a, b):
        a, b = deref(a), deref(b)
        if a is b:
            return True
        if isinstance(a, Var):
            self.bind(a, b)
            return True
        if isinstance(b, Var):
            self.bind(b, a)
            return True
        if isinstance(a, int) and isinstance(b, int):
            return a == b and not isinstance(a, bool)
        if isinstance(a, (Cons, Vec)) and type(a) is type(b):
            if len(a.args) != len(b.args):
                return False
            return all(self.unify(x, y) for x, y in zip(a.args, b.args))
        # A string unifies only with itself: the same storage (logical
        # address of the first element, its position in the word, element
        # length and count).  TM-388 PDF p79 (folio 67): 'abc'='abc', == and
        # =:= all fail, equal_string/2 succeeds; p117-119 (folio 105-107),
        # unify rule (iii)b and Table 4-3; p169 (folio 157), ESP's "ABC" =
        # "ABC" fails; TM-115 PDF p97 (folio 92).  A Str object is one stored
        # string here, so identity is `is` (tested above).
        if isinstance(a, ClassRef) and a == b:
            return True
        return False

    # -- running -----------------------------------------------------------
    def reset(self):
        self.sender = None
        self.x = collections.defaultdict(Var)
        self.env = None
        self.cont = None
        self.b0 = 0
        self.stack = []
        self.trail = []
        self.S = None
        self.steps = 0

    def fail(self):
        if not self.stack:
            self.pc = None
            return
        ch = self.stack[-1]
        while len(self.trail) > ch.trail:
            self.trail.pop().ref = None
        self.x = collections.defaultdict(Var, ch.x)
        self.env, self.cont, self.b0 = ch.env, ch.cont, ch.b0
        self.pc = ch.alt

    def cut_to(self, b):
        del self.stack[b:]

    def solve(self, start, args, limit=None):
        """Generator of solutions: START is (code, offset) or a Syn; ARGS
        go to A0... ; yields after each success (the caller reads ARGS)."""
        self.reset()
        for i, a in enumerate(args):
            self.x[i] = a
        self.pc = (start, 0) if isinstance(start, Syn) else start
        self.cont = ('halt',)
        self.b0 = 0
        while True:
            if self.pc is None:
                return
            if self.pc == ('halt',):
                yield True
                self.fail()
                continue
            self.steps += 1
            if self.steps > self.max_steps:
                raise StepLimit(self.steps)
            self.exec1()

    def exec1(self):
        code, off = self.pc
        if isinstance(code, Syn):
            return self.syn(code, off)
        c = code.cells.get(off)
        if c is None:
            raise Refusal('code', '%s: no cell at @%x' % (code.id, off))
        tag = c[1]
        if self.trace:
            self.trace(code, c)
        if tag in (0x20, 0x21):
            key = ('pmi' if tag == 0x20 else 'blt', '%02x' % (c[3] >> 24))
            fn = self.handlers.get(key)
            if fn is None:
                raise Refusal('opcode', '%s %s (%s @%x)' % (key[0], key[1], code.id, off))
            v = c[3]
            return fn(code, off, (v >> 16) & 255, (v >> 8) & 255, v & 255, v)
        if tag == 0x60:
            lo = c[2]
            if lo & 0x80:
                key = ('atom', 'put')
            elif lo == 0x4c:
                key = ('atom', 'unify')
            else:
                key = ('atom', 'get')
            fn = self.handlers.get(key)
            if fn is None:
                raise Refusal('opcode', 'atom cell %s (%s @%x)' % (key[1], code.id, off))
            return fn(code, off, lo, Atom(code.sym(c[3])))
        if tag == 0xa0:
            fn = self.handlers.get(('table', '%04x' % c[2]))
            if fn is None:
                raise Refusal('opcode', 'hash table %04x (%s @%x)' % (c[2], code.id, off))
            return fn(code, off, c)
        raise Refusal('code', '%s @%x: execution reached a data cell (%s)' % (
            code.id, off, P.show(dict(syms=code.t.symbols), c)))

    def nxt(self, code, off, k=1):
        self.pc = (code, off + k)

    def operand(self, code, off):
        c = code.cells.get(off + 1)
        if c is None:
            raise Refusal('code', '%s: no operand cell at @%x' % (code.id, off + 1))
        return c

    def const_cell(self, code, c):
        if c[1] == 0x00:
            v = c[3]
            return v - (1 << 32) if v & 0x80000000 else v
        if c[1] == 0x01 and c[2] == 0:
            return Atom(code.sym(c[3]))
        raise Refusal('operand', '%s: constant cell %s' % (code.id, P.show(dict(syms=code.t.symbols), c)))

    def key_cell(self, code, c):
        """A cc constant or a hash key: as const_cell, and also the vector
        key cell (tag 01, low byte N != 0) that follows a `pmi ce`
        (Functor, step 3g)."""
        if c[1] == 0x01 and c[2] != 0:
            return Functor(code.sym(c[3]), c[2])
        return self.const_cell(code, c)

    @staticmethod
    def key_match(k, t):
        return (isinstance(k, int) and isinstance(t, int) and t == k) or \
            (isinstance(k, (Atom, Functor)) and t is k)

    # -- calls -------------------------------------------------------------
    def call_local(self, code, off, target, last, dealloc=False):
        p = code.preds.get(target)
        if p is None:
            raise Refusal('code', '%s @%x: local call to @%x, not a predicate' % (code.id, off, target))
        if dealloc:
            self.cont, self.env = self.env.cont, self.env.prev
        elif not last:
            self.cont = (code, off + 1, self.env, self.b0)
        if p.kind != 0x12:
            # a $or$N (kind 0x12) keeps the caller's barrier: OURS
            self.enter_pred(p)
        self.pc = (code, target)

    def enter_pred(self, p):
        """A predicate's entry barrier: in B0, and in register A_arity."""
        self.b0 = len(self.stack)
        self.x[p.arity] = Barrier(self.b0)

    def proceed(self):
        k = self.cont
        if k == ('halt',):
            self.pc = ('halt',)
            return
        code, off, env, b0 = k
        # the caller's own continuation is held in its environment
        self.env, self.b0 = env, b0
        self.cont = env.cont if env is not None else ('halt',)
        self.pc = (code, off)

    # -- method dispatch ---------------------------------------------------
    def send(self, code, off, R, n, sel_cell, last, dealloc=False):
        if sel_cell[1] != 0x01 or sel_cell[2] == 0:
            raise Refusal('code', '%s @%x: no selector after the send' % (code.id, off))
        name, arity = code.sym(sel_cell[3]), sel_cell[2]
        recv = deref(self.x[R])
        self.sender = code.id   # the sending class (lib_class_named)
        if dealloc:
            self.cont, self.env = self.env.cont, self.env.prev
        elif not last:
            self.cont = (code, off + 2, self.env, self.b0)
        self.dispatch(recv, name, arity)

    def dispatch(self, recv, name, arity):
        if self.stop_before and (name, arity) in self.stop_before:
            raise CreatorStopped(name, arity, [deref(self.x[i]) for i in range(arity)])
        if isinstance(recv, ClassRef):
            cid, section = recv.cid, 'class'
        elif isinstance(recv, Instance):
            cid, section = recv.cid, 'instance'
        elif isinstance(recv, Var):
            raise Refusal('unbound receiver', 'send %s/%d to an unbound receiver' % (name, arity))
        elif isinstance(recv, SlotConstant):
            raise Refusal('receiver a slot constant', 'send %s/%d to %r' % (name, arity, recv))
        else:
            raise Refusal('receiver not an object', 'send %s/%d to %r' % (name, arity, recv))
        if cid == 'simpos##undefined_method' and name == 'raise' and arity == 2:
            # the receiver is last (register 1), the information first
            raise Raised(resolve(self.x[0]))
        model = SIMPOS_MODELS.get((cid, section, name, arity))
        if model is not None:
            return model(self)
        if cid not in self.lib.templates:
            raise Refusal('simpos', 'send %s:%s/%d (%s class not loaded)' % (cid, name, arity, section))
        co = self.lib.build(cid)
        m = self.lib.send(co, section, name, arity)
        if m is None and (name, arity) == ('refute', 3):
            return self.refute()
        if m is None or not m.primaries:
            if section == 'class' and (name, arity) == ('new', 2):
                # class `class`'s new/2 (TM-388 §3.6), OURS, as the primary
                return self.run_combined(co, m, ('new',))
            if not co.complete:
                raise Refusal('simpos', 'send %s:%s/%d (not in the held classes; ancestors %s)' % (
                    cid, name, arity, ' '.join(r for r, _s in co.opaque)))
            if m is None and getattr(self.lib.templates.get(cid), 'standin', False):
                # a stand-in (psi/standin/, OURS) has only some of the
                # lost class's methods: the rest is still SIMPOS
                raise Refusal('simpos', 'send %s:%s/%d (not in the stand-in)' % (cid, name, arity))
            partial = [c for c in co.order if getattr(self.lib.templates.get(c), 'standin', False)]
            if partial:
                # step 3e: an ancestor is a stand-in, which holds only part
                # of the lost class, so a missing primary may be in the
                # lost part: still SIMPOS, as for an unloaded ancestor
                raise Refusal('simpos', 'send %s:%s/%d (no primary in the held classes; stand-in ancestors %s)'
                              % (cid, name, arity, ' '.join(partial)))
            if m is None:
                # not in the class's own table: a method of class `class`
                # (not held, other than new/2), or one a mixin leaves to
                # the class it is mixed into
                raise Refusal('no method', '%s %s:%s/%d is not in the class' % (section, cid, name, arity))
        return self.run_combined(co, m, None)

    def refute(self):
        """Class `class`'s :refute(Object, Method, ArgVector) (TM-388 p.46,
        PDF p.58): the dynamic method call.  OURS: the vector's elements
        are the arguments after the receiver, in order."""
        name, args, obj = deref(self.x[0]), deref(self.x[1]), deref(self.x[2])
        if not isinstance(name, Atom):
            raise Refusal('unbound argument' if isinstance(name, Var) else 'built-in',
                          'refute method name %r' % (name,))
        if not isinstance(args, Vec):
            raise Refusal('unbound argument' if isinstance(args, Var) else 'built-in',
                          'refute argument vector %r' % (args,))
        n = len(args.args)
        for i, a in enumerate(args.args):
            self.x[i] = a
        self.x[n] = obj
        return self.dispatch(obj, name.name, n + 1)

    def run_combined(self, co, m, prim):
        """TM-388 §3.4: b1..bn, (p1;...;pk;fail), a.. as synthetic code."""
        before = m.before if m else []
        after = m.after if m else []
        primaries = [('class', None)] if prim == ('new',) else list(m.primaries)
        if not before and not after and len(primaries) == 1 and primaries[0][0] != 'class':
            cid, p = primaries[0]
            self.enter_pred(p)
            self.pc = (self.code(cid), p.offset)
            return
        n = m.selector[1] if m else 2
        ops = [('save', n)]
        for cid, p in before:
            ops += [('restore', n), ('call', cid, p.offset)]
        if not primaries:
            ops.append(('fail',))
        heads, jumps = [], []
        for k, (cid, p) in enumerate(primaries):
            heads.append(len(ops))
            if len(primaries) > 1:
                ops.append(('try', None) if k == 0 else (('retry', None) if k + 1 < len(primaries) else ('trust',)))
            ops.append(('restore', n))
            ops.append(('new', co.id) if cid == 'class' else ('call', cid, p.offset))
            jumps.append(len(ops))
            ops.append(('jump', None))
        for k in range(len(primaries) - 1):
            ops[heads[k]] = (ops[heads[k]][0], heads[k + 1])
        for j in jumps:
            ops[j] = ('jump', len(ops))
        for cid, p in after:
            ops += [('restore', n), ('call', cid, p.offset)]
        ops.append(('return',))
        self.pc = (Syn('%s:%s/%d' % (co.id, m.selector[0] if m else 'new', n), ops), 0)

    def syn(self, code, off):
        op = code.ops[off]
        k = op[0]
        if k == 'save':
            self.env = Frame(op[1], self.env, self.cont, len(self.stack))
            for i in range(op[1]):
                self.env.y[i] = self.x[i]
            return self.nxt(code, off)
        if k == 'restore':
            for i in range(op[1]):
                self.x[i] = self.env.y[i]
            return self.nxt(code, off)
        if k == 'call':
            self.cont = (code, off + 1, self.env, self.b0)
            c = self.code(op[1])
            self.enter_pred(c.preds[op[2]])
            self.pc = (c, op[2])
            return
        if k == 'new':
            self.cont = (code, off + 1, self.env, self.b0)
            self.class_new(op[1])
            return
        if k == 'try':
            ch = Choice((code, op[1]), self)
            self.stack.append(ch)
            return self.nxt(code, off)
        if k == 'retry':
            self.stack[-1].alt = (code, op[1])
            return self.nxt(code, off)
        if k == 'trust':
            self.stack.pop()
            return self.nxt(code, off)
        if k == 'jump':
            self.pc = (code, op[1])
            return
        if k == 'fail':
            return self.fail()
        if k == 'halt':
            self.pc = ('halt',)
            return
        if k == 'return':
            env = self.env
            self.env = env.prev
            self.cont = env.cont
            return self.proceed()
        raise Refusal('code', 'synthetic op %r' % (op,))

    # -- SIMPOS's library and atom table (step 3f, OURS) --------------------
    # Not held, and not writable as ESP stand-ins: they answer from the
    # loader's own tables (the Librarian, psi/librarian.py, OURS) and from
    # the atom table.  Each method below names the call sites it is
    # INTERPOLATED from; what is not modelled refuses.

    def lib_class_named(self, name):
        """The loaded class an atom names: `pkg##c` exactly; else `c` in
        the package of the class that sent the library call; else the one
        loaded class `*##c`.  None if none is loaded; refused if several
        are.  INTERPOLATED: the own package first is the static lookup rule
        of a bare class name, PRINTED in TM-388 PDF p94 (folio 82: "(1)
        every class in the self package") and the p95 worked example
        (subsystems/librarian.md §1.4; ESP manual program-e.tex:5250-5934).
        TM-388 binds it when a class is stored (PDF p93, folio 81) and
        at macro expansion (p98, folio 86), and says nothing of a run-time
        lookup (pp92-101 read as images, 2026-11-25); that the run-time lookup
        follows it, and that the "own" package is the sender's (not the
        process's default package, kappa2 HLCLIB.ESP:30-31 `:get_package(
        Process, P)`), are INFERENCE (gaps.md, librarian row 1: the
        resolution order is not known)."""
        if '##' in name:
            return name if name in self.lib.templates else None
        own = '%s##%s' % ((self.sender or '').split('##')[0], name)
        if own in self.lib.templates:
            return own
        hits = [c for c in self.lib.templates if c.split('##', 1)[1] == name]
        if len(hits) > 1:
            raise Refusal('simpos', 'library: %s names %s' % (name, ' '.join(hits)))
        return hits[0] if hits else None

    def library_assign(self):
        """:assign(#library).  INTERPOLATED from: the call sites, each the
        first library send of its clause, before check_info/3,
        get_class_object/3 or make_package/2 (kappa2 kernel/hlc/HLCLIB.ESP:29,
        utility/tool/LOADCH.ESP:64, LOADER.ESP:251; pimfep
        pimos_string_io_invoker create_string_io/10 @2e-31, and the other
        pimfep/pimscsi sends the plain census stopped at).  What it binds
        is UNKNOWN (gaps.md, librarian row 4); it succeeds and changes
        nothing here."""
        self.proceed()

    def library_check_info(self):
        """:check_info(#library, Name, Kind).  INTERPOLATED from: kappa2
        LOADER.ESP:252-256 and pimfep pimos_string_io_invoker local
        get_class_object/3 (@5a-80), which try Kind `template_file` (then
        make_class_object/2) and `object`, and then get_class_object/3
        (LOADER `object` first, pimfep `template_file` first: step 3g's
        re-check, source_check_2026-11-24.md §7; either order answers
        the same here).  get_class_object/c2 and enter_atom/c2 are
        printed in TR-283 PDF p18 (folio 16) Table 4.
        OURS: every class here is loaded as a class object, so `object`
        succeeds for a loaded class and `template_file` fails."""
        name, kind = deref(self.x[0]), deref(self.x[1])
        if isinstance(name, Var) or isinstance(kind, Var):
            raise Refusal('unbound argument', 'library check_info/3 on %r, %r' % (name, kind))
        if not isinstance(name, Atom) or not isinstance(kind, Atom) or \
                kind.name not in ('object', 'template_file'):
            raise Refusal('simpos', 'library check_info/3 on %r, %r' % (name, kind))
        if kind.name == 'object' and self.lib_class_named(name.name):
            return self.proceed()
        return self.fail()

    def library_get_class_object(self):
        """:get_class_object(#library, Name, Class).  INTERPOLATED from the
        same call sites and fep_services.md §6.4 (601: "the class object of
        that name is taken from simpos##library").  A class not loaded here
        is refused (fail or raise is not known, gaps.md librarian row 1)."""
        name = deref(self.x[0])
        if not isinstance(name, Atom):
            raise Refusal('unbound argument' if isinstance(name, Var) else 'simpos',
                          'library get_class_object/3 on %r' % (name,))
        cid = self.lib_class_named(name.name)
        if cid is None:
            raise Refusal('simpos', 'library get_class_object/3: %s is not loaded' % name.name)
        return self.proceed() if self.unify(self.x[1], ClassRef(cid)) else self.fail()

    def symbolizer_enter_atom(self):
        """:enter_atom(#symbolizer, Atom, String).  PRINTED interface: TR-283
        p18 (folio 16) Table 4 lists :enter_atom/c2 of class symbolizer,
        atom <-> string conversion.  The direction and argument order are
        INTERPOLATED from the call sites: paragraph p_wshell.esp:211 and
        304-305 (`substring(C0,1,Len-1,C1), :enter_atom(#symbolizer,Var,C1),
        :get_at(Obj!var,St,Var)`: the string second, the atom first and
        then used as a key) and pimfep pimos_string_io_invoker
        create_string_io/10 @28-2d (A0 a new variable, A1 the 16-bit name
        string tested at @1d-1e).  The atom is the string's text (OURS)."""
        s = deref(self.x[1])
        if not isinstance(s, Str):
            raise Refusal('unbound argument' if isinstance(s, Var) else 'built-in',
                          'symbolizer enter_atom/3 on %r' % (s,))
        return self.proceed() if self.unify(self.x[0], Atom(s.text)) else self.fail()

    def process_suspend(self):
        """:suspend(Process, Reason), refused (step 3g, OURS).  The printed
        body (TM-100 Fig. 3.1, standin/process.esp) is not run: kl0 runs
        one process and has no scheduler, so a process that suspends here
        (stream get/2 or see/2 on an empty stream) waits for a put or a
        resume that nothing can make.  Run, the printed body would fail
        for the census's process (status nil: `:self(#process, P)` makes
        it with new/2 and nothing activates it), and the wait would show
        as a clean failure.  So it refuses, cause 'would suspend'."""
        reason = resolve(self.x[0])
        raise Refusal('would suspend', 'process suspend/2 on %r: one process, no scheduler' % (reason,))

    def class_new(self, cid):
        """OURS stand-in for class `class`'s new/2 (TM-388 §3.6): the new
        instance, with constant and `is Class` slot values and the values of
        its slot-initialisation predicates (TM-388 pp.49-50: if one fails,
        new fails); A0 := it."""
        try:
            inst = new_instance(self.lib, cid, self)
        except InitFailed:
            return self.fail()
        if not self.unify(self.x[0], inst):
            return self.fail()
        self.proceed()

    def new_object(self, q, e):
        """`slot is Q` (TM-388 p.49): :new(#Q, Obj) on its own (OURS: a
        sub-machine, first solution, as init_value); InitFailed if new fails."""
        sub = Machine(self.lib, self.rows, max_steps=self.max_steps)
        depth = getattr(self, 'init_depth', 0)
        if depth > 50:
            raise Refusal('slot init', 'slot %s of %s: initialisation nested over 50 deep' % (e.name, e.owner))
        sub.codes, sub.class_slots, sub.init_depth = self.codes, self.class_slots, depth + 1
        v = Var()
        run = sub.solve_send(ClassRef(q), 'new', [v, ClassRef(q)])
        try:
            if not any(True for _ in run):
                raise InitFailed(e)
        finally:
            run.close()
        return deref(v)

    def init_value(self, e):
        """Run slot entry E's initialisation predicate (arity 1, value in
        A0: MEASURED) on its own, to its first solution (OURS).  -> the
        value, resolved; raises InitFailed if the predicate fails."""
        p = e.slot.init[1]
        if p is None:
            raise Refusal('code', 'slot %s of %s: no initialisation predicate' % (e.name, e.owner))
        depth = getattr(self, 'init_depth', 0)
        if depth > 50:
            raise Refusal('slot init', 'slot %s of %s: initialisation nested over 50 deep' % (e.name, e.owner))
        sub = Machine(self.lib, self.rows, max_steps=self.max_steps)
        sub.codes, sub.class_slots, sub.init_depth = self.codes, self.class_slots, depth + 1
        v = Var()
        run = sub.solve(Syn('%s slot %s init' % (e.owner, e.name),
                            [('call', e.owner, p.offset), ('halt',)]), [v])
        try:
            if not any(True for _ in run):
                raise InitFailed(e)
        finally:
            run.close()
        val = resolve(v)
        if has_var(val):
            raise Refusal('slot init unbound', 'slot %s of %s: value %r' % (e.name, e.owner, val))
        return val

    def slot_index(self, obj, name):
        if isinstance(obj, Instance):
            co, sec = self.lib.build(obj.cid), 'instance'
        elif isinstance(obj, ClassRef):
            if obj.cid not in self.lib.templates:
                raise Refusal('simpos', 'slot %s of %s' % (name, obj.cid))
            co, sec = self.lib.build(obj.cid), 'class'
        else:
            raise Refusal('unbound receiver' if isinstance(obj, Var) else
                          'receiver a slot constant' if isinstance(obj, SlotConstant) else
                          'receiver not an object', 'slot %s of %r' % (name, obj))
        k = self.lib.slot_number(co, sec, name)
        if k is None:
            raise Refusal('simpos' if not co.complete else 'no slot', 'slot %s of %s' % (name, co.id))
        return co, sec, k

    def slot_store(self, obj, co, sec):
        if sec == 'instance':
            return obj.slots
        s = self.class_slots.get(co.id)
        if s is None:
            # the class is generated: its class slots take their initial
            # values (TM-388 p.49), computed at first access (OURS)
            s = self.class_slots[co.id] = [None if e.slot.init[0] == 'code' else slot_value(e.slot)
                                           for e in co.class_slots]
            for k, e in enumerate(co.class_slots):
                if e.slot.init[0] == 'code':
                    try:
                        s[k] = self.init_value(e)
                    except InitFailed:
                        del self.class_slots[co.id]
                        raise Refusal('class not generated', '%s class slot %s: its initialisation fails'
                                      % (co.id, e.name))
        return s

    # -- structure cursor (read and write modes are one here) ---------------
    def enter(self, term, args):
        self.S = [term.args, 0] if args is None else [args, 0]

    def next_elem(self):
        if self.S is None or self.S[1] >= len(self.S[0]):
            raise Refusal('code', 'unify instruction with no structure element left')
        el, i = self.S
        self.S[1] += 1
        return el, i

    def get_struct(self, A, kind, n):
        t = deref(self.x[A])
        if isinstance(t, Var):
            new = Cons(Var(), Var()) if kind == 'list' else Vec([Var() for _ in range(n)])
            self.bind(t, new)
            self.S = [new.args, 0]
            return True
        if kind == 'list' and isinstance(t, Cons):
            self.S = [t.args, 0]
            return True
        if kind == 'vec' and isinstance(t, Vec) and len(t.args) == n:
            self.S = [t.args, 0]
            return True
        return False

