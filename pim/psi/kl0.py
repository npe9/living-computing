class InitFailed(Exception):
    """A slot-initialisation predicate failed (TM-388 p.50: new fails)."""


def has_var(t):
    t = deref(t)
    if isinstance(t, Var):
        return True
    if isinstance(t, (Cons, Vec)):
        return any(has_var(a) for a in t.args)
    return False


def new_instance(lib, cid, m=None):
    """An instance as the OURS new/2 makes it.  Slots initialised by code
    run their predicate on machine M (InitFailed if one fails); without M
    they refuse (cause 'slot init by code')."""
    co = lib.build(cid)
    slots = []
    for e in co.instance_slots:
        if e.slot.init[0] == 'code':
            if m is None:
                raise Refusal('slot init by code', '%s slot %s' % (cid, e.name))
            slots.append(m.init_value(e))
        elif e.slot.init[0] == 'is' and m is not None:
            # `slot is Class`: "Generate an instance object for the class
            # ... and store it as the slot value" (TM-388 p.49, (3))
            slots.append(m.new_object(e.slot.init[1], e))
        else:
            slots.append(slot_value(e.slot))
    return Instance(cid, slots)


def make_instance(m, cid):
    """A fresh instance for a census call; if a slot-initialisation
    predicate fails, new/2 would fail: refused as 'new fails'."""
    m.reset()
    try:
        return new_instance(m.lib, cid, m)
    except InitFailed as e:
        raise Refusal('new fails', '%s: slot %s initialisation fails' % (cid, e.args[0].name))


