def recipe_instance(m, cid, recipes):
    """The census receiver for an instance method: by CID's recipe if it
    has one, else new/2 (make_instance)."""
    r = recipes.get(cid) if recipes else None
    return r(m) if r is not None else make_instance(m, cid)


def census(m=None, max_steps=20000):
    """Every method of the classes that need no SIMPOS, called once with
    unbound arguments (the receiver: the class, or a fresh instance).
    -> list of (class, section, selector, outcome, cause, detail).  Outcome:
    'success' (a first solution), 'failure' (clean, no solution), 'refused',
    'exception' (an uncaught `:raise(#undefined_method, ...)`, step 3e),
    'step limit'.  Success, failure and exception count as running to
    completion."""
    if m is None:
        m = Machine(load_six(), max_steps=max_steps)
    six = list(m.lib.templates)
    return census_of(m, m.lib.free_of_simpos(six, 'union'))


def census_of(m, classes, recipes=None, reverse=False):
    """census(): every method of CLASSES, each called once.  RECIPES
    (step 3f): class -> a function making the instance receiver (RECIPES
    above); a class without one gets new/2's instance.

    Each row starts from freshly generated class objects (step 3i, OURS):
    the class slots are dropped before every call, so they take their
    initial values again on first access (TM-388 p.49), and the census
    process (stand-in process's class slot `current`) is a new one.  A
    row's outcome is then what it is alone on a fresh machine, whatever
    rows ran before it.  Before step 3i one machine's class slots were
    shared by every row, so a row could read what an earlier row left
    (pimfep_message_log dump_log/1 read the `log_table` that
    set_log_table/2 had set to an unbound variable; resign/1 and
    resign_core/1 popped a program that an earlier row's assign/1 had
    pushed on the shared process's stack; psi/README.md "Step 3i").  REVERSE runs
    the classes and each class's methods in the opposite order (the test
    of that independence, test_espc.py test_step3i_census_order)."""
    rows = []
    for cid in (list(classes)[::-1] if reverse else classes):
        co = m.lib.build(cid)
        calls = [(section, name, n)
                 for section, table in (('class', co.class_methods), ('instance', co.instance_methods))
                 for (name, n) in table]
        for section, name, n in (calls[::-1] if reverse else calls):
            m.class_slots = {}
            rows.append(census_row(m, cid, section, name, n, recipes))
    return rows


def census_row(m, cid, section, name, n, recipes=None):
    """One census row: NAME/N of CID called once with unbound arguments
    (census_of above).  -> (class, section, selector, outcome, cause,
    detail)."""
    sel = '%s/%d' % (name, n)
    try:
        # step 3g: a request for a device command handler
        # (REQUEST_ID), only where the receiver has a recipe
        lead = (request_args(m, cid, name, n)
                if section == 'instance' and recipes and cid in recipes else [])
        recv = ClassRef(cid) if section == 'class' else recipe_instance(m, cid, recipes)
        regs = lead + [Var() for _ in range(n - 1 - len(lead))] + [recv]
        ok = any(True for _ in m.solve_send(recv, name, regs))
        return (cid, section, sel, 'success' if ok else 'failure', '', '')
    except Refusal as e:
        return (cid, section, sel, 'refused', e.cause, e.detail)
    except Raised as e:
        return (cid, section, sel, 'exception', 'raise', repr(e.info))
    except StepLimit:
        return (cid, section, sel, 'step limit', '', '')


FEP_PACKAGES = ('pimfep', 'pimscsi')


def fep_machine(max_steps=20000):
    """The six packages plus the stand-ins of psi/standin/ (espc.py)."""
    import espc
    lib = load_six()
    for t in espc.standins():
        lib.add(t)
    return Machine(lib, max_steps=max_steps)


def census_fep(m=None, recipes=None):
    """The census of pimfep's and pimscsi's methods (PIM/m's front end,
    docs/simpos/README.md §5), stand-ins loaded, in template order.
    RECIPES=RECIPES makes the receivers of those classes by their held
    creators (step 3f); the default is new/2 for every class."""
    if m is None:
        m = fep_machine()
    return census_of(m, [cid for cid in m.lib.templates if cid.split('##')[0] in FEP_PACKAGES], recipes)


def simpos_target(detail):
    """'send C:S/N (...)' -> 'C:S/N' (the class and selector a refusal
    stopped at), else the detail's first word."""
    if detail.startswith('send '):
        return detail[5:].split(' (')[0]
    return detail.split(' ')[0]


def refusal_key(cause, detail):
    """The ranking key: the opcode for a missing opcode, else the cause."""
    if cause == 'opcode':
        return 'missing opcode ' + ' '.join(detail.split()[:2])
    if cause == 'simpos':
        return 'simpos## call'
    return cause


def main(argv):
    if argv and argv[0] == 'convert':
        r = convert_report()
        c = collections.Counter(x[3] for x in r['rows'])
        for name, f, p, st in r['rows']:
            if st != 'equal':
                print('%-20s fep %-10s pimos %-10s %s' % (name, f, p, st))
        print('codes answered: %d; names answered: %d; against pimos.vmac: %s; (_,_) gives %d solutions' % (
            len(r['by_code']), len(r['by_name']), dict(c), len(r['both_unbound'])))
        print('names a code -> name call does not return (an earlier clause with the same code cuts): %s'
              % ' '.join(r['shadowed']))
        return 0
    if argv and argv[0] == 'census':
        rows = (census_fep(recipes=RECIPES if '--recipes' in argv else None)
                if '--fep' in argv else census())
        c = collections.Counter(r[3] for r in rows)
        print('%d methods of %d classes: %s' % (len(rows), len({r[0] for r in rows}), dict(c)))
        rk = collections.Counter(refusal_key(r[4], r[5]) for r in rows if r[3] == 'refused')
        for k, v in rk.most_common():
            print('  %5d  %s' % (v, k))
        if '--fep' in argv:
            st = collections.Counter(simpos_target(r[5]) for r in rows
                                     if r[3] == 'refused' and r[4] == 'simpos')
            print('simpos## calls, by the class and selector reached:')
            for k, v in st.most_common(25):
                print('  %5d  %s' % (v, k))
        if '--tsv' in argv:
            with open(argv[argv.index('--tsv') + 1], 'w') as f:
                f.write('class\tsection\tselector\toutcome\tcause\tdetail\n')
                for r in rows:
                    f.write('\t'.join(r) + '\n')
        return 0
    if argv and argv[0] == 'call':
        m = Machine(load_six())
        cid, sel = argv[1], argv[2]
        name, n = sel.split('/')
        args = []
        for a in argv[3:]:
            args.append(int(a) if a.lstrip('-').isdigit() else (Var() if a == '_' else Atom(a)))
        for s in call_class_method(m, cid, name, args):
            print(s)
        return 0
    print(__doc__)
    return 2


