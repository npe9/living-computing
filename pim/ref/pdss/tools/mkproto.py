#!/usr/bin/env python3
"""Second mechanical step after knr2ansi.py: prototypes.

    mkproto.py PROTOS SRCDIR

PROTOS is knr2ansi.py --protos output (file, storage, prototype).
Writes SRCDIR/proto.h with one prototype per external function of the
emulator and pdssasm (pdssmerge.c, a separate program, and table.c, a
macro template, are left out), inserts each file's static prototypes
after its last top-level #include, and deletes the K&R function
declarations ("extern foo();", "static OBJ *bar();") that the
prototypes replace, in the headers and at file scope.
"""
import collections
import os
import re
import sys

protos_path, src = sys.argv[1], sys.argv[2]
ext, sta = collections.OrderedDict(), collections.defaultdict(list)
for line in open(protos_path):
    f, storage, p = line.rstrip("\n").split("\t")
    name = re.search(r"(\w+)\(", p).group(1)
    if f in ("pdssmerge.c", "table.c"):
        continue
    if storage == "static":
        if p not in sta[f]:
            sta[f].append(p)
    elif name != "main":
        ext.setdefault(name, (f, p))

# conflicting duplicates (same name, different prototype) are reported
seen = {}
for line in open(protos_path):
    f, storage, p = line.rstrip("\n").split("\t")
    if f in ("pdssmerge.c", "table.c") or storage == "static":
        continue
    name = re.search(r"(\w+)\(", p).group(1)
    if name in seen and seen[name] != p and name != "main":
        print("CONFLICT %s: %s | %s" % (name, seen[name], p), file=sys.stderr)
    seen.setdefault(name, p)

with open(os.path.join(src, "proto.h"), "w") as out:
    out.write("/* Prototypes of PDSS's external functions, generated once by\n"
              "   tools/mkproto.py from the definitions (then maintained by hand). */\n\n")
    cur = None
    for name, (f, p) in ext.items():
        if f != cur:
            out.write("\n/* %s */\n" % f)
            cur = f
        out.write("extern " + p + "\n")

names = set(ext)
decl = re.compile(r"^(?P<ind>\s*)(?:extern\s+|static\s+)?(?:unsigned\s+|struct\s+)?"
                  r"(?:[A-Za-z_]\w*(?=[\s*])\s*)?\**\s*\b(?P<name>[A-Za-z_]\w*)\(\);\s*(/\*.*\*/)?\s*$")
for fn in sorted(os.listdir(src)):
    if not (fn.endswith(".c") or fn.endswith(".h")) or fn in ("pdssmerge.c", "table.c", "proto.h"):
        continue
    path = os.path.join(src, fn)
    lines = open(path, encoding="latin-1").read().split("\n")
    statics = {re.search(r"(\w+)\(", p).group(1) for p in sta.get(fn, [])}
    out, last_inc, removed = [], -1, 0
    for line in lines:
        m = decl.match(line)
        if m and not m.group("ind") and (m.group("name") in names or m.group("name") in statics):
            removed += 1
            continue
        if line.startswith("#include") and "table.c" not in line:
            last_inc = len(out)
        out.append(line)
    if sta.get(fn):
        block = ["", "/* Static functions (prototypes generated by tools/mkproto.py). */"] + sta[fn]
        out[last_inc + 1:last_inc + 1] = block
    open(path, "w", encoding="latin-1").write("\n".join(out))
    if removed or sta.get(fn):
        print("%s: %d K&R declarations removed, %d static prototypes" % (fn, removed, len(sta.get(fn, []))))
