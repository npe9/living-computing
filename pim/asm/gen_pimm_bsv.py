#!/usr/bin/env python3
"""Generate what the Bluespec PIM/m core shares with the decoders.

    python3 asm/gen_pimm_bsv.py OUTDIR

writes
  OUTDIR/PimmGen.bsv    tag constants (asm/kbn.py TAGS, from PIMOS's
                        debugger/inspector/tagtbl.kl1) and opcode
                        constants {tag, opcode} (docs/kl1_encoding.md,
                        from library/assembler/inst_tab.kl1), the
                        load address, and each predicate's code
                        address in the IPL image (asm/kbndis.py)
  OUTDIR/pimm_ipl.hex   the IPL image pimm_ipl.kbn, one 40-bit cell per
                        line (tag, then value), cell 0 = the load
                        address, followed by the built-in stubs
                        (asm/pimm_stubs.py), zero-filled to the
                        memory size

Nothing in the Bluespec source types a tag or an opcode by hand.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kbn  # noqa: E402
import kbndis  # noqa: E402
from census import opcode_table  # noqa: E402

import pimm_layout as L  # noqa: E402
import pimm_stubs  # noqa: E402


def main(argv):
    out = argv[1]
    os.makedirs(out, exist_ok=True)
    lines = ['// Generated by asm/gen_pimm_bsv.py.  Do not edit.',
             'package PimmGen;', '',
             'typedef %d AddrBits;' % L.ADDR_BITS, '']
    for v, name in sorted(kbn.TAGS.items()):
        ident = re.sub(r'\W.*', '', name)
        lines.append("Bit#(8) tag_%s = 8'h%02x;" % (ident, v))
    lines.append('')
    seen = set()
    for (tag, op), names in sorted(opcode_table().items()):
        name = names[0]
        if name in seen:
            continue
        seen.add(name)
        lines.append("Bit#(16) op_%s = 16'h%02x%02x;" % (name, tag, op))
    # the built-in stubs (asm/pimm_stubs.py): by opcode, where the
    # stub is, how many operands, which are outputs (bit k = operand k)
    from unlsav import load_opcodes
    enc = {}
    for op, ents in load_opcodes().items():
        for name, _typ, tag in ents:
            enc.setdefault(name, (tag, op))
    _stubs, table = pimm_stubs.build(len(kbn.decode(kbn.image())[1]))
    lines += ['', 'typedef struct { Bit#(AddrBits) addr; Bit#(3) n; Bit#(7) outs; } Stub',
              '  deriving (Bits);', '',
              'function Maybe#(Stub) stubOf(Bit#(16) op);', '  case (op)']
    for name, e in table.items():
        if name.startswith('$'):
            continue
        outs = sum(1 << k for k, d in enumerate(e['dirs']) if d == 'o')
        lines.append("    16'h%02x%02x: return tagged Valid Stub { addr: %d, n: %d, outs: 7'h%02x };  // %s"
                     % (enc[name][0], enc[name][1], e['addr'], len(e['dirs']), outs, name))
    lines += ['    default: return tagged Invalid;', '  endcase', 'endfunction', '',
              '// the merger step (asm/pimm_stubs.py: ours, not a PIM/m instruction)',
              "Bit#(16) op_merge_in = 16'h2200;",
              'Bit#(AddrBits) mergeInStub = %d;' % table['$merge_in']['addr'],
              "Bit#(16) op_unify_step = 16'h2201;",
              'Bit#(AddrBits) unifyStepStub = %d;' % table['$unify_step']['addr'],
              "// Goal@processor(P), P unbound: the goal of to_processor N waits (ours)",
              "Bit#(16) op_to_processor = 16'h2202;",
              'Bit#(AddrBits) toProcStub = %d;   // to_processor N at toProcStub + 2 N' % table['$to_processor0']['addr'],
              "// a shoen's first goal is a goal of apply's stub (PimmShBox.bsv)",
              'Bit#(AddrBits) applyStub = %d;' % table['apply']['addr'], '']
    # the address of every predicate's first instruction
    im = kbndis.Image()
    lines += ['', "Bit#(32) loadAddress = 32'h%08x;" % im.load,
              'Integer heapStart = %d;' % L.HEAP, '']
    for k in ('G_LINK', 'G_STATUS', 'G_CODE', 'G_ARGN', 'G_ARGS', 'READY',
              'SUSPENDED', 'TAKEN', 'S_NEXT', 'S_GOAL', 'S_SIZE',
              'SH_COUNT', 'SH_STATUS', 'SH_PARENT', 'SH_REPORT', 'SH_GOAL', 'SH_SIZE',
              'DORMANT', 'STARTED', 'TERMINATED', 'REPORT_STARTED', 'REPORT_TERMINATED',
              'SH_REDUCTIONS', 'SH_REMOVE', 'REMOVED', 'REPORT_STATISTICS_STARTED',
              'REPORT_STATISTICS', 'REPORT_RETURN_RESOURCE',
              'SH_MASK', 'STOPPED', 'REPORT_ABORTED', 'REPORT_EXCEPTION', 'REPORT_STOPPED',
              'EXC_REDUCTION_FAILURE', 'EXC_RAISED', 'REPORT_RESOURCE_ADDED',
              'REPORT_RESOURCE_REPORT_ALLOWED'):
        lines.append('Integer lay_%s = %d;' % (k, getattr(L, k)))
    lines.append('')
    for m in im.mods:
        for name, _ln, addr in m['preds']:
            ident = 'pred_%s__%s' % (m['name'], name.replace('/', '_'))
            if re.fullmatch(r'\w+', ident, re.A) and ident not in seen:
                seen.add(ident)
                lines.append('Integer %s = %d;' % (ident, addr))
    lines += ['', 'endpackage', '']
    with open(os.path.join(out, 'PimmGen.bsv'), 'w') as f:
        f.write('\n'.join(lines))
    got, cells = kbn.decode(kbn.image())[:2]
    stubs, table = pimm_stubs.build(len(cells))
    cells = list(cells) + stubs
    # the cells below the heap only: the heap is not loaded (PimmMem.bsv)
    assert len(cells) <= L.HEAP == 1 << 15 <= L.MEMORY_CELLS
    with open(os.path.join(out, 'pimm_ipl.hex'), 'w') as f:
        for t, v in cells:
            f.write('%02x%08x\n' % (t, v))
        for _ in range(L.HEAP - len(cells)):
            f.write('0000000000\n')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
