#!/usr/bin/env python3
"""check_strap2_7030_optab.py -- the 7030 STRAP II's operation tables
(decks/strap2_7030.strap, step 4a-iii), generated by strap/strap2/optab7030.py
from the host's optable.py, read back, and searched on the Bluespec model.

THE MEMBERSHIP is IBM's printed operation set (tests/printed_ops.py: C28-6129
Apps. A and C, N28-1081, the guide's App. B) as the host accepts it, plus the
listing-witnessed CBRZ+ CBRZ- CBRZH, without the branch-on-indicator family
(p.22: MIBA supplies those, "not in the op table").  No host-order spelling
and no over-accepted form is in it.

Checks:
  block_fresh   the deck's generated block is what the generator makes now
  decode        the deck, assembled by the host STRAP II, read back through
                optab7030.decode: every entry's kind, length, alignment,
                question bits, fill chain, secondary code and skeleton (for
                an ambiguous op, the floating first half and the VFL last
                half) equal optable.lookup's
  secondaries   SECTAB's fifteen entries are Fig. 24's for the rule
  order         OPTAB and SECTAB ascend, so BOPSER may search them
  7030 runs     the model's BOPSER (p.67 linkage) on OPCB for every name and
                for misses (below the first, above the last, a name with its
                last code one higher), and on SECCB likewise: LLXW on a find,
                not-found otherwise, each equal to strap2/bopser.py's

Run from stretch/tests with PYTHONDONTWRITEBYTECODE=1.

MEASURED 2026-11-15: 472 ops, 97 op misses, 15 secondaries, 5 secondary
misses; 3.4M model steps, about five minutes.

MEASURED INJECTIONS (each restored from a saved copy and checked with cmp;
control all passing):
  the generator's Zoimm moved to bit 60, block   2: block_fresh, decode
    not regenerated
  LN's word 2 hand-edited in the deck            2: block_fresh, decode
  LN and LNA swapped in the deck                 3: block_fresh, order, and
                                                    the host's own search
                                                    (the model agrees with it)
  the deck's BOPSER Box 3 counting from 2        2: the 7030 ops, the 7030
    (N one short)                                   secondaries
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "strap"))
sys.path.insert(0, HERE)
import strap_asm                                    # noqa: E402
import strap2                                       # noqa: E402
from strap2 import bopser, optab7030 as O, optable as T  # noqa: E402
from strap2.bits import BitMem                      # noqa: E402
from strap2.cards import deck_cards                 # noqa: E402
from check_strap2_7030 import BSV                   # noqa: E402
import printed_ops                                  # noqa: E402

DECK = os.path.join(HERE, "..", "decks", "strap2_7030.strap")
MODULE = "StretchStrap2x7030OptabTb"
STEPS = 40000000
MISS = (1 << 24) - 1
fails = 0


def check(label, got, want):
    global fails
    if got == want:
        print(f"PASS {label}")
    else:
        fails += 1
        print(f"FAIL {label}: got {str(got)[:600]}, want {str(want)[:300]}")


def assemble(text):
    return strap2.compile_cards(deck_cards(text), strap_asm.DEFAULT_ORIGIN_BITS)


def driver(searches):
    """searches: [(control block, test word, key)]."""
    L = ["START   NOP"]
    for i, (cb, tw, _) in enumerate(searches):
        L += [f"        L(BU,64), KEY+{i}.0", f"        ST(BU,64), {tw}",
              "        SIC, $15", "        B, BOPSER", f"        , {cb}",
              f"        B, NF{i}", "        L(BU,24), LLXW", f"        B, ST{i}",
              f"NF{i}    L(BU,24), BDMISS",
              f"ST{i}    ST(BU,24), RES+{i}.0"]
    L += ["DONE    BEW, $", "        CNOP",
          f"BDMISS  DD(BU,64), (16){MISS << 40:016X}",
          "KEY     SYN, $"]
    L += [f"        DD(BU,64), (16){k:016X}" for _, _, k in searches]
    L += [f"RES     DRZ(BU,64), {len(searches)}"]
    return "\n".join(L) + "\n"


def deck_text(searches):
    src = open(DECK).read()
    assert src.endswith("        END\n")
    return src[:-len("        END\n")] + driver(searches) + "        END, START\n"


def misses_of(names):
    return [names[0] - 1, names[-1] + 1] + [n + 1 for n in names[::5] if n + 1 not in names]


def main():
    src = open(DECK).read()
    tb = O.Tables(printed_ops.optab_names()).layout()
    i, j = src.find(O.BEGIN), src.find(O.END)
    block = src[i:j + len(O.END) + 1] if i >= 0 and j > i else None
    check("block_fresh: the deck's OPTAB block is the generator's", block == tb.deck_text(), True)

    base = assemble(deck_text([("OPCB", "OPKEY", 0)]))
    word = lambda n: base.val.symbol_value(base.st.search(n))[0] // 64
    ws = base.image.words
    at = lambda a: ws.get(a, 0)
    dec = O.decode(at, word("OPTAB"), len(tb.order), tb.routines)
    bad = []
    for n in tb.order:
        e, d = T.lookup(n), dec.get(n)
        if d is None:
            bad.append((n, "missing"))
            continue
        want = O.attributes(n, e)
        for k, v in want.items():
            if d.get(k) != v:
                bad.append((n, k, d.get(k), v))
    check(f"decode: all {len(tb.order)} entries read back as optable.lookup's",
          (len(dec), bad[:8]), (len(tb.order), []))
    sec = [(at(word("SECTAB") + 2 * k), at(word("SECTAB") + 2 * k + 1))
           for k in range(len(O.secondaries()))]
    check("secondaries: SECTAB is Fig. 24's fifteen entries",
          sec, [(a, b) for a, b, _ in O.secondaries()])
    prim = [at(word("OPTAB") + 2 * k) for k in range(len(tb.order))]
    check("order: OPTAB and SECTAB ascend",
          (prim == sorted(prim), [a for a, _ in sec] == sorted(a for a, _ in sec)), (True, True))

    pm, sm = misses_of(prim), misses_of([a for a, _ in sec])
    searches = ([("OPCB", "OPKEY", k) for k in prim + pm] +
                [("SECCB", "SECKEY", a) for a, _ in sec] + [("SECCB", "SECKEY", k) for k in sm])
    p2 = assemble(deck_text(searches))
    word = lambda n: p2.val.symbol_value(p2.st.search(n))[0] // 64
    mem = BitMem()
    for w, v in p2.image.words.items():
        mem.put(64 * w, 64, v)
    want = []
    for cb, tw, k in searches:
        mem.put(64 * word(tw), 64, k)
        r = bopser.bopser(mem, 64 * word(cb))
        want.append(r.llxw if r.found else MISS)
    np_, ns = len(prim), len(sec)
    check("control: the host finds every op at its own entry's function",
          want[:np_], [64 * word("OPTAB") + 128 * k + 64 for k in range(np_)])
    s0 = np_ + len(pm)
    check("control: the host finds every secondary at its own entry",
          want[s0:s0 + ns], [64 * word("SECTAB") + 128 * k + 64 for k in range(ns)])
    check("control: the host finds none of the misses",
          set(want[np_:s0] + want[s0 + ns:]), {MISS})
    res = word("RES")
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, MODULE + ".strap")
        with open(path, "w") as fh:
            fh.write(deck_text(searches))
        args = [os.path.join(HERE, "run_program.sh"), path, MODULE, "ASM=strap2",
                f"STEPS={STEPS}", f"CYCLES<={STEPS}",
                f"FASTLOAD={os.path.join(tmp, MODULE + '.hex')}",
                f"ERRC:{word('ERRC')}=0x0"]
        args += [f"R{i}:{res + i}=0x{v << 40:x}" for i, v in enumerate(want)]
        r = subprocess.run(args, capture_output=True, text=True, cwd=HERE)
    for name in os.listdir(BSV):            # by exact name, never a glob
        if name in (MODULE + ".bsv", MODULE + "_sim", MODULE + "_sim.so"):
            os.remove(os.path.join(BSV, name))
    out = r.stdout
    if r.returncode or "step cap" in out:
        check("the run", (out + r.stderr)[-800:], "ok")
        return
    rf = [int(f[1:]) for f in re.findall(r"^FAIL (R\d+)", out, re.M)]
    check("ERRC is 0", bool(re.search(r"^PASS ERRC", out, re.M)), True)
    check(f"7030: every one of the {np_} ops found at bopser.py's LLXW",
          [f for f in rf if f < np_], [])
    check(f"7030: every one of the {len(pm)} op misses not found",
          [f for f in rf if np_ <= f < s0], [])
    check(f"7030: every one of the {ns} secondaries found, and {len(sm)} misses not",
          [f for f in rf if f >= s0], [])
    m = re.search(r"cycles = (\d+)", out)
    print(f"INFO model steps: {m.group(1) if m else '?'}")


if __name__ == "__main__":
    main()
    if fails:
        print(f"*** {fails} CHECK(S) FAILED ***")
        sys.exit(1)
    print("ALL CHECKS PASSED")
