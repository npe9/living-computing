def hw(loc, k):
    """The half-word location k half-words after octal `loc`."""
    b = loc_bits(loc) + 32 * k
    return f"{b // 64:06o}.{b % 64:02o}"


def nops(start, n, what):
    return [(hw(start, i), NOP, f"{what} NOP {i + 1}") for i in range(n)]


def zeros(start, n, what):
    return [(f"{start + i:06o}.00", Z22, f"{what} word {i + 1}")
            for i in range(n)]


def inject_loop(sx_ub, store_row, nop_start, kv, tail):
    """One single-error injection loop: SX,$X7,$UB / [CNOP] / the store
    (SX,$X8 or Z) / CNOP / Z,$UB / five NOPs, blank, five NOPs, blank /
    KV / BXEZ / V+I / CBR."""
    return ([(sx_ub, "3.17 10", "SX,$X7,$UB"), store_row,
             (hw(store_row[0], 1), NOP, "CNOP"),
             (hw(store_row[0], 2), "3.22 00", "Z,$UB")]
            + nops(nop_start, 5, "first five")
            + nops(hw(nop_start, 5), 5, "second five")
            + [kv] + tail)


