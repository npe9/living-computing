def image_source():
    """The deck's text: the image both this check and run_ja_bb6b.sh use.
    A live PUNFUL card is refused rather than silently dropped."""
    text = open(DECK).read()
    for line in text.splitlines():
        if line.split("!", 1)[0].strip().upper().rstrip(",") == "PUNFUL":
            raise SystemExit("ja_bb6b: a live PUNFUL card would load nothing")
    return text


