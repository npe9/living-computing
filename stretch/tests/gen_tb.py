#!/usr/bin/env python3
"""gen_tb.py -- generate a runnable Bluespec testbench that loads an
assembled STRAP program's memory image into mkStretchCore, runs it
until the "BEW, $" self-branch halt idiom fires (core.halted(); see
StretchCore.bsv's interface comment -- step() advances one clock), and
checks a caller-supplied list of expected final memory words.

This is the loader half of the codesign loop: strap_asm.py's output
feeds a BSV module built entirely from constructs already proven not
to trip the write-conflict issues recorded in bsv/README.md
"Toolchain" (one core.mem.writeWord per phase, an explicit phase
register rather than mkAutoFSM/StmtFSM).
"""

import sys

from strap_asm import assemble, AssemblerError


def generate(module_name, prog, checks, step_cap=30000, reader_image=None,
             console_switches=None,
             printer_checks=None, tape_image=None, tape_checks=None,
             console_checks=None,
             pc_check=None, cycle_bound=None, ipl=False, pc_trail=False,
             pc_trail_check=None, op_trail=False):
    """checks: list of (label:str, word_addr_expr:str, expected:int).

    reader_image: optional list of ints -- words to pre-load into the
    simulated card reader (StretchIO.chanReader) before the program
    runs, via core.io.loadReaderWord, one write per phase exactly like
    the program-word loader below (see StretchIO.bsv's file header for
    why this reuses that pattern instead of real file I/O).

    console_checks: optional list of (label:str, device_index:int,
    expected:int) -- the same against core.io.readConsoleWord, for what
    a program WROTE TO THE OPERATOR'S CONSOLE (StretchIO.chanConsole).

    printer_checks: optional list of (label:str, device_index:int,
    expected:int) -- checked the same way as `checks` but against
    core.io.readPrinterWord(index) instead of core.mem.readWord(addr),
    for verifying what a WRITE instruction actually sent to the
    simulated printer (StretchIO.chanPrinter).

    tape_image: optional list of ints -- words to pre-load into the
    simulated tape (StretchIO.chanTape) before the program runs, via
    core.io.writeTapeWord -- the same method the running program's own
    W instructions use, since the tape is bidirectional (see
    StretchIO.bsv's file header).

    tape_checks: optional list of (label:str, tape_index:int,
    expected:int) -- checked against core.io.readTapeWord(index),
    for verifying tape content a W instruction wrote (as distinct from
    checks against core storage, which verify what an RD read back).
    """
    words = sorted(prog.words.items())
    reader_image = reader_image or []
    # THE OPERATOR SETS THESE BEFORE PRESSING IPL.  Reference Manual
    # printed p.150 gives the console "a word weight of 3" and says a
    # READ returns "the three words scanned from the switches";
    # C22-6678-1 printed p.29 step 2 says what goes in them ("Set up
    # the time in binary keys 0-23, and the date in binary keys
    # 32-55").  Loaded exactly the way reader_image is, one write per
    # phase, so the program starts with the console already set.
    console_switches = console_switches or []
    printer_checks = printer_checks or []
    console_checks = console_checks or []
    tape_image = tape_image or []
    tape_checks = tape_checks or []
    if prog.end_pc is None:
        raise ValueError("program has no END target; cannot set the start PC")

    lines = []
    lines.append(f"// Auto-generated by stretch/tests/gen_tb.py -- do not edit by hand.")
    lines.append(f"package {module_name};")
    lines.append("")
    lines.append("import StretchTypes::*;")
    lines.append("import StretchStorage::*;")
    lines.append("import StretchIO::*;")
    lines.append("import StretchCore::*;")
    lines.append("")
    lines.append("(* synthesize *)")
    lines.append(f"module mk{module_name}(Empty);")
    lines.append("  StretchCore core <- mkStretchCore;")
    lines.append("  Reg#(Bit#(32)) phase <- mkReg(0);")
    lines.append("  Reg#(Bit#(32)) stepCount <- mkReg(0);")
    if pc_trail:
        # WHERE DID IT GO?  A halt reports the PC it stopped at, and
        # that is enough while the program stops somewhere it meant
        # to.  It stops being enough the moment a program branches
        # into storage that holds zeros: a zero half-word is
        # BRANCH ENABLED to 0.0 (UNCOND_BRANCH_CODES["BE"] is 0b000
        # with a zero address field), so EVERY such run reports PC 0
        # and they all look alike.  The last NON-ZERO pc is the
        # branch's destination, which names it.
        #
        # EARNED ITS KEEP ON ITS FIRST RUN, 2026-10-23: the MCP boot
        # run's "PC 0" turned out to be 002166.00, which printed p.37
        # line 45 calls S PRIME, "LOCATION OF PRIME ROUTINE" -- so
        # MCP had FINISHED initialization and handed off, rather than
        # got lost.  Opt-in, because it costs a $display on every run
        # that asks for it.
        lines.append("  Reg#(HWordAddr) pcTrail0 <- mkReg(0);")
        lines.append("  Reg#(HWordAddr) lastNonZeroPc <- mkReg(0);")
    if op_trail:
        # WHICH INSTRUCTION DID THE MODEL REFUSE?  An unimplemented
        # operation sets the OP indicator and the program carries on
        # into its own error routine, so by the time the checks run
        # the PC is wherever that routine ended and the refusal's
        # address is gone.  This latches it.
        #
        # THE PC IT REPORTS IS THE ONE SAMPLED THE CLOCK BEFORE OP
        # WENT HIGH, which is a LOCATOR AND NOT A PROOF: this model
        # has a look-ahead, so getPC() is the instruction unit's
        # counter and can be running ahead of the operation that set
        # the bit.  Use it to find the row, then read the row.
        lines.append("  Reg#(HWordAddr) opTrailPc <- mkReg(0);")
        lines.append("  Reg#(Bit#(32)) opTrailStep <- mkReg(0);")
        lines.append("  Reg#(Bool) opTrailSeen <- mkReg(False);")
        lines.append("  Reg#(Bool) opTrailWas <- mkReg(False);")
        lines.append("  Reg#(HWordAddr) opTrailLastPc <- mkReg(0);")
        lines.append("  Reg#(Bit#(32)) opTrailCount <- mkReg(0);")
    lines.append("  Reg#(Bit#(32)) fails <- mkReg(0);")
    lines.append("")
    lines.append("  function Action check(String label, Word64 got, Word64 expected) =")
    lines.append("    action")
    lines.append("      if (got == expected)")
    lines.append('        $display("PASS %s = %0d (0x%0x)", label, got, got);')
    lines.append("      else begin")
    lines.append('        $display("FAIL %s = %0d (0x%0x), expected %0d (0x%0x)", label, got, got, expected, expected);')
    lines.append("        fails <= fails + 1;")
    lines.append("      end")
    lines.append("    endaction;")
    lines.append("")

    # INITIAL PROGRAM LOAD: the tape puts the program in core, so the
    # harness must NOT.  Pre-loading it would make the test pass even
    # if the IPL read moved nothing -- the whole point is that core
    # storage starts empty and the tape fills it.
    words = [] if ipl else words
    n_load = len(words)
    # With ipl=True there is nothing to load, and an empty `case` is a
    # bsc error (P0075, "Case statement with no clauses"), so the rule
    # is omitted rather than emitted empty.
    if n_load:
        lines.append(f"  rule load (phase < {n_load} && core.mem.writeReady());")
        lines.append("    case (phase)")
        for i, (addr, val) in enumerate(words):
            lines.append(f"      {i}: core.mem.writeWord({addr}, 64'h{val:016x});")
        lines.append("    endcase")
        lines.append("    phase <= phase + 1;")
        lines.append("  endrule")
        lines.append("")

    n_reader = len(reader_image)
    reader_load_phase = n_load
    if n_reader:
        lines.append(f"  rule loadReader (phase >= {reader_load_phase} && phase < {reader_load_phase + n_reader});")
        lines.append(f"    case (phase - {reader_load_phase})")
        for i, val in enumerate(reader_image):
            lines.append(f"      {i}: core.io.loadReaderWord({i}, 64'h{val & ((1<<64)-1):016x});")
        lines.append("    endcase")
        lines.append("    phase <= phase + 1;")
        lines.append("  endrule")
        lines.append("")

    n_switch = len(console_switches)
    switch_load_phase = reader_load_phase + n_reader
    if n_switch:
        lines.append(f"  rule loadSwitches (phase >= {switch_load_phase} && phase < {switch_load_phase + n_switch});")
        lines.append(f"    case (phase - {switch_load_phase})")
        for i, val in enumerate(console_switches):
            lines.append(f"      {i}: core.io.setConsoleSwitchWord({i}, 64'h{val & ((1<<64)-1):016x});")
        lines.append("    endcase")
        lines.append("    phase <= phase + 1;")
        lines.append("  endrule")
        lines.append("")

    n_tape = len(tape_image)
    tape_load_phase = switch_load_phase + n_switch
    if n_tape:
        lines.append(f"  rule loadTape (phase >= {tape_load_phase} && phase < {tape_load_phase + n_tape});")
        lines.append(f"    case (phase - {tape_load_phase})")
        for i, val in enumerate(tape_image):
            lines.append(f"      {i}: core.io.writeTapeWord({i}, 64'h{val & ((1<<64)-1):016x});")
        lines.append("    endcase")
        lines.append("    phase <= phase + 1;")
        lines.append("  endrule")
        lines.append("")

    run_phase = tape_load_phase + n_tape
    lines.append(f"  rule setStart (phase == {run_phase});")
    if ipl:
        # Reference Manual printed p.126.  No setPC: the entry point
        # comes from the control word the tape's first word becomes,
        # which is the thing under test.
        lines.append("    core.iplStart();")
    else:
        lines.append(f"    core.setPC({prog.end_pc});")
    lines.append(f"    phase <= {run_phase + 1};")
    lines.append("  endrule")
    lines.append("")

    run_phase += 1
    lines.append(f"  rule run (phase == {run_phase} && !core.halted() && stepCount < {step_cap});")
    lines.append("    core.step();")
    if pc_trail:
        lines.append("    pcTrail0 <= core.getPC();")
        lines.append("    if (core.getPC() != 0) lastNonZeroPc <= core.getPC();")
    if op_trail:
        # EVERY 0->1 EDGE, not just the first: MCP's interruption
        # system CLEARS the indicator once it has taken it, so a run
        # can refuse several operations and finish with the bit low.
        #
        # >>> THE COUNT IS A LOWER BOUND AND THE FIRST ADDRESS IS THE
        # FINDING. <<<  Measured 2026-10-23 on the MCP boot: the run
        # reports ONE edge, at half-word 1304, and ends with OP SET,
        # while the control run with printed p.45 taken out of the
        # image reports ONE edge at the SAME address and ends with OP
        # CLEAR.  One edge each does not by itself account for two
        # different endings, so something -- a clear and a re-set
        # between two samples, or a difference between
        # mem.readIndicators() and the word 11 the checks read -- is
        # not being seen here.  That is RECORDED AND NOT GUESSED AT;
        # docs/NEXT.md carries it.  What the trail is trusted for is
        # the ADDRESS of the first raise, which the control run
        # reproduces exactly.
        lines.append("    opTrailWas <= (core.mem.readIndicators()[64 - 1 - 15] == 1);")
        lines.append("    if (!opTrailWas && core.mem.readIndicators()[64 - 1 - 15] == 1) begin")
        lines.append("      opTrailCount <= opTrailCount + 1;")
        lines.append("      opTrailLastPc <= core.getPC();")
        lines.append("      if (!opTrailSeen) begin")
        lines.append("        opTrailSeen <= True;")
        lines.append("        opTrailPc <= core.getPC();")
        lines.append("        opTrailStep <= stepCount;")
        lines.append("      end")
        lines.append("    end")
    lines.append("    stepCount <= stepCount + 1;")
    lines.append("  endrule")
    lines.append("")
    lines.append(f"  rule afterRun (phase == {run_phase} && (core.halted() || stepCount == {step_cap}));")
    lines.append(f"    if (!core.halted()) begin")
    lines.append(f"      $display(\"FAIL: step cap ({step_cap}) reached without halting -- checks below run against mid-execution state\");")
    lines.append(f"      fails <= fails + 1;")
    lines.append(f"    end")
    if pc_trail:
        lines.append('    $display("PC TRAIL: last non-zero half-word address %0d, after %0d steps", lastNonZeroPc, stepCount);')
    if op_trail:
        lines.append("    if (opTrailSeen)")
        lines.append('      $display("OP TRAIL: operation invalid raised %0d times; first at half-word address %0d after %0d steps, last at %0d", opTrailCount, opTrailPc, opTrailStep, opTrailLastPc);')
        lines.append("    else")
        lines.append('      $display("OP TRAIL: operation invalid never set");')
    lines.append(f"    phase <= {run_phase + 1};")
    lines.append("  endrule")
    lines.append("")

    # Each check is two phases: issue the read, then collect it once
    # core.mem.responseReady() says the memory units have answered
    # (variable latency -- docs/microarchitecture_plan.md stage 1).
    # The loader likewise waits for writeReady(), since stores queue
    # behind busy memory units.
    check_phase0 = run_phase + 1
    for i, (label, addr_expr, expected) in enumerate(checks):
        req_phase = check_phase0 + 2 * i
        resp_phase = req_phase + 1
        lines.append(f"  rule checkReq{i} (phase == {req_phase});")
        lines.append(f"    core.mem.readWordReq({addr_expr});")
        lines.append(f"    phase <= {resp_phase};")
        lines.append("  endrule")
        lines.append("")
        lines.append(f"  rule checkResp{i} (phase == {resp_phase} && core.mem.responseReady());")
        lines.append(f"    let v{i} <- core.mem.readWordResp();")
        lines.append(f'    check("{label}", v{i}, 64\'h{expected & ((1<<64)-1):016x});')
        lines.append(f"    phase <= {resp_phase + 1};")
        lines.append("  endrule")
        lines.append("")

    pcheck_phase0 = check_phase0 + 2 * len(checks)
    for i, (label, dev_idx, expected) in enumerate(printer_checks):
        lines.append(f"  rule pcheck{i} (phase == {pcheck_phase0 + i});")
        lines.append(f'    check("{label}", core.io.readPrinterWord({dev_idx}), 64\'h{expected & ((1<<64)-1):016x});')
        lines.append(f"    phase <= {pcheck_phase0 + i + 1};")
        lines.append("  endrule")
        lines.append("")

    # CONSOLE CHECKS -- what MCP printed.  Same shape as the printer's
    # above, against core.io.readConsoleWord, because the console's
    # paper is a device image and not a word of storage.
    ccheck_phase0 = pcheck_phase0 + len(printer_checks)
    for i, (label, dev_idx, expected) in enumerate(console_checks):
        lines.append(f"  rule ccheck{i} (phase == {ccheck_phase0 + i});")
        lines.append(f'    check("{label}", core.io.readConsoleWord({dev_idx}), 64\'h{expected & ((1<<64)-1):016x});')
        lines.append(f"    phase <= {ccheck_phase0 + i + 1};")
        lines.append("  endrule")
        lines.append("")

    tcheck_phase0 = ccheck_phase0 + len(console_checks)
    for i, (label, tape_idx, expected) in enumerate(tape_checks):
        lines.append(f"  rule tcheck{i} (phase == {tcheck_phase0 + i});")
        lines.append(f'    check("{label}", core.io.readTapeWord({tape_idx}), 64\'h{expected & ((1<<64)-1):016x});')
        lines.append(f"    phase <= {tcheck_phase0 + i + 1};")
        lines.append("  endrule")
        lines.append("")

    # Final instruction-counter check ("PC=EXPECTED"): where the
    # program halted. A branch to itself halts this model (StretchCore
    # halted() becomes True when next == pc), which is exactly the I-Box
    # diagnostics' own "BD,$" hang-on-failure idiom -- so a verbatim
    # diagnostic block can be run with its own pass/fail mechanism
    # intact: pass = halted at the block's end, fail = halted at the
    # offending hang, distinguishable by PC alone.
    pccheck_phase = tcheck_phase0 + len(tape_checks)
    # Cycle bound ("CYCLES<=N"): the run rule fires once per clock, so
    # stepCount at halt is the program's cycle count on this model
    # (one step() = one clock of the microarchitecture model, docs/
    # microarchitecture_plan.md). A separate check from the architectural ones
    # so a timing regression never masquerades as a wrong result.
    if cycle_bound is not None:
        lines.append(f"  rule cyclecheck (phase == {pccheck_phase});")
        lines.append(f"    if (stepCount <= {cycle_bound})")
        lines.append(f'      $display("PASS cycles = %0d (bound {cycle_bound})", stepCount);')
        lines.append("    else begin")
        lines.append(f'      $display("FAIL cycles = %0d, bound {cycle_bound}", stepCount);')
        lines.append("      fails <= fails + 1;")
        lines.append("    end")
        lines.append(f"    phase <= {pccheck_phase + 1};")
        lines.append("  endrule")
        lines.append("")
        pccheck_phase += 1
    if pc_check is not None:
        lines.append(f"  rule pccheck (phase == {pccheck_phase});")
        lines.append(f'    check("PC (half-word address)", zeroExtend(core.getPC()), {pc_check});')
        lines.append(f"    phase <= {pccheck_phase + 1};")
        lines.append("  endrule")
        lines.append("")
        pccheck_phase += 1
    # THE LAST NON-ZERO PC, AS A CHECK AND NOT ONLY A MESSAGE.
    #
    # pc_trail above explains why a run that branches into zeroed
    # storage reports PC 0: a zero half-word is BRANCH ENABLED to 0.0,
    # so the counter sits at zero for the rest of the run and
    # `pc_check` can only assert the value every such run has.  The
    # TRAIL is the datum in that case -- the last address the program
    # reached under its own control -- and a $display is not a check.
    #
    # Requires pc_trail (the register it reads is only declared then).
    if pc_trail_check is not None:
        assert pc_trail, "pc_trail_check needs pc_trail"
        lines.append(f"  rule pctrailcheck (phase == {pccheck_phase});")
        lines.append('    check("last non-zero PC (half-word address)", '
                     f'zeroExtend(lastNonZeroPc), {pc_trail_check});')
        lines.append(f"    phase <= {pccheck_phase + 1};")
        lines.append("  endrule")
        lines.append("")
        pccheck_phase += 1

    finish_phase = pccheck_phase
    lines.append(f"  rule finish (phase == {finish_phase});")
    lines.append("    if (fails == 0)")
    lines.append('      $display("ALL TESTS PASSED");')
    lines.append("    else")
    lines.append('      $display("%0d TEST(S) FAILED", fails);')
    lines.append("    $finish(0);")
    lines.append("  endrule")
    lines.append("")
    lines.append("endmodule")
    lines.append("")
    lines.append("endpackage")
    return "\n".join(lines) + "\n"


if __name__ == '__main__':
    # Simple CLI: gen_tb.py program.strap ModuleName [ARG ...], where ARG is
    # one of:
    #   LABEL:ADDR=EXPECTED    -- a core-storage check (as before)
    #   P:LABEL:INDEX=EXPECTED -- a simulated-printer-word check (INDEX is a
    #                             plain device index 0..DeviceWords-1, not a
    #                             STRAP expression, since the printer has no
    #                             addressing of its own -- see StretchIO.bsv)
    #   R=W0,W1,W2,...         -- pre-load the simulated card reader's image
    #                             with these words, in order, index 0 first
    #                             (int(x,0), so hex "0x..." or decimal both
    #                             work); at most one R= argument is allowed
    #   T=W0,W1,W2,...         -- pre-load the simulated tape's image, same
    #                             syntax as R=; at most one T= argument
    #   CYCLES<=N              -- check that the run halted within N clock
    #                             cycles (stepCount); the timing oracle,
    #                             kept separate from the result checks
    #   PC=EXPECTED            -- check the instruction counter (a 19-bit
    #                             half-word address) where the program
    #                             halted; see the pccheck rule above
    #   TC:LABEL:INDEX=EXPECTED -- a simulated-tape-word check (INDEX is a
    #                             plain tape index 0..TapeWords-1), for
    #                             verifying what a W instruction wrote to
    #                             tape -- see StretchIO.bsv
    if len(sys.argv) < 3:
        print(f"usage: {sys.argv[0]} program.strap ModuleName "
              f"[LABEL:ADDR=EXPECTED | P:LABEL:INDEX=EXPECTED | "
              f"TC:LABEL:INDEX=EXPECTED | R=W0,W1,... | T=W0,W1,... ...]",
              file=sys.stderr)
        sys.exit(1)
    with open(sys.argv[1]) as f:
        src = f.read()
    try:
        prog = assemble(src)
    except AssemblerError as e:
        print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    module_name = sys.argv[2]
    checks = []
    printer_checks = []
    tape_checks = []
    reader_image = None
    tape_image = None
    pc_check = None
    cycle_bound = None
    # STEPS=N raises the run rule's step cap.  A deck needs this when
    # it executes instructions the TIMING MODEL charges heavily for:
    # the cap counts core.step() calls, and an instruction's budget
    # holds the machine for its duration.  Store Root is 108 clocks
    # (Perf. Char. Table 2, printed p.3-5: 2 pre-execution + 106
    # execution), so a deck doing several of them needs a cap sized
    # for that, not for the flat 3 every floating-point instruction
    # used to cost.
    step_cap = 30000
    for spec in sys.argv[3:]:
        if spec.startswith('PC='):
            pc_check = int(spec[3:], 0)
        elif spec.startswith('STEPS='):
            step_cap = int(spec[6:], 0)
        elif spec.startswith('CYCLES<='):
            cycle_bound = int(spec[8:], 0)
        elif spec.startswith('R='):
            reader_image = [int(x, 0) for x in spec[2:].split(',') if x]
        elif spec.startswith('T='):
            tape_image = [int(x, 0) for x in spec[2:].split(',') if x]
        elif spec.startswith('P:'):
            label, rest = spec[2:].split(':', 1)
            idx_expr, expected = rest.split('=', 1)
            printer_checks.append((label, int(idx_expr, 0), int(expected, 0)))
        elif spec.startswith('TC:'):
            label, rest = spec[3:].split(':', 1)
            idx_expr, expected = rest.split('=', 1)
            tape_checks.append((label, int(idx_expr, 0), int(expected, 0)))
        else:
            label, rest = spec.split(':', 1)
            addr_expr, expected = rest.split('=', 1)
            checks.append((label, addr_expr, int(expected, 0)))
    print(generate(module_name, prog, checks, step_cap=step_cap,
                    reader_image=reader_image,
                    printer_checks=printer_checks, tape_image=tape_image,
                    tape_checks=tape_checks, pc_check=pc_check,
                    cycle_bound=cycle_bound))
