def image_source():
    """The deck's text: the image both this check and run_ja_bm6a.sh use.
    A live PUNFUL card is refused rather than silently dropped."""
    text = open(DECK).read()
    for line in text.splitlines():
        if line.split("!", 1)[0].strip().upper().rstrip(",") == "PUNFUL":
            raise SystemExit("ja_bm6a: a live PUNFUL card would load nothing")
    return text


