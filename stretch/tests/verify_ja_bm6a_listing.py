#!/usr/bin/env python3
"""verify_ja_bm6a_listing.py -- assemble ../decks/ja_bm6a_unique_adr.strap
(IBM's JA BM6A "UNIQUE ADDRESS TESTS", May 5, 1961,
docs/ja_bm6a_unique_adr_test.pdf PDF pp.4-11) and compare every
assembled word against the machine code printed beside each line -- see
strap/listing_oracle.py.

THE WHOLE PROGRAM IS CHECKED: every symbol is defined inside the
listing (TYPE by its own SYN on PDF p.11), so every address-bearing row
is a genuine address-placement check.

WHAT IS NOT CHECKED:
  - 001016.40, "B,GEN1": the page is torn there (PDF p.4's last line);
    only "101" of the printed code survives.
  - 001076.00, the eight-zero-byte (16)DD on PDF p.6's last line: the
    source is legible but the printed word is under the tear's ink
    (only scattered zeros and the final "00" show).
  - PRNID, SEM, PUNFUL, SLC and CNOP-with-no-code print no code.
  TYPE's SYN prints "23.40+" and a second group "+00000000" with no
  location; it is checked as the symbol's value (TYPE = 000023.40).

PUNFUL.  The deck is "PUNFUL binary ... 13 cards" (writeup PDF p.1,
3.1.1).  The printed "PUNFUL," card is commented out in the deck for
the reason ja_bp6a gives (with it, strap_asm loads nothing).

Run standalone: `./verify_ja_bm6a_listing.py`. Wired into run_tests.sh.
"""

