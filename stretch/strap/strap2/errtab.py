TABLES = {"C22-6729": GUIDE, "N28-1081": N28_1081}
SERIOUS = {"C22-6729": 28, "N28-1081": 18}


def message(number, table="C22-6729"):
    """The message as printed: its text and its number."""
    if table not in TABLES:
        raise ValueError(f"no error list {table!r}; have {sorted(TABLES)}")
    return f"{TABLES[table].get(number, 'SPARE')}  {number}"


def serious(number, table="C22-6729"):
    return 1 <= number <= SERIOUS[table]
