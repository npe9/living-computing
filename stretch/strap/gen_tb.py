#!/usr/bin/env python3
"""gen_tb.py -- generate a runnable Bluespec testbench that loads an
assembled STRAP program's memory image into mkStretchCore, runs it
until the "BEW, $" self-branch halt idiom fires (see StretchCore.bsv's
step() docstring), and checks a caller-supplied list of expected final
memory words.

This is the loader half of the codesign loop: strap_asm.py's output
feeds a BSV module built entirely from constructs already proven not
to trip the write-conflict issues recorded in bsv/README.md
"Toolchain" (one core.mem.writeWord per phase, an explicit phase
register rather than mkAutoFSM/StmtFSM).
"""

import sys

from strap_asm import assemble, AssemblerError


def generate(module_name, prog, checks, step_cap=30000, reader_image=None,
             printer_checks=None, tape_image=None, tape_checks=None,
             pc_check=None, cycle_bound=None):
    """checks: list of (label:str, word_addr_expr:str, expected:int).

    reader_image: optional list of ints -- words to pre-load into the
    simulated card reader (StretchIO.chanReader) before the program
    runs, via core.io.loadReaderWord, one write per phase exactly like
    the program-word loader below (see StretchIO.bsv's file header for
    why this reuses that pattern instead of real file I/O).

    printer_checks: optional list of (label:str, device_index:int,
    expected:int) -- checked the same way as `checks` but against
    core.io.readPrinterWord(index) instead of core.mem.readWord(addr),
    for verifying what a WRITE instruction actually sent to the
    simulated printer (StretchIO.chanPrinter).

    tape_image: optional list of ints -- words to pre-load into the
    simulated tape (StretchIO.chanTape) before the program runs, via
    core.io.writeTapeWord -- the same method the running program's own
    W instructions use, since the tape is bidirectional (see
    StretchIO.bsv's file header).

    tape_checks: optional list of (label:str, tape_index:int,
    expected:int) -- checked against core.io.readTapeWord(index),
    for verifying tape content a W instruction wrote (as distinct from
    checks against core storage, which verify what an RD read back).
    """
    words = sorted(prog.words.items())
    reader_image = reader_image or []
    printer_checks = printer_checks or []
    tape_image = tape_image or []
    tape_checks = tape_checks or []
    if prog.end_pc is None:
        raise ValueError("program has no END target; cannot set the start PC")

    lines = []
    lines.append(f"// Auto-generated by stretch/strap/gen_tb.py -- do not edit by hand.")
    lines.append(f"package {module_name};")
    lines.append("")
    lines.append("import StretchTypes::*;")
    lines.append("import StretchStorage::*;")
    lines.append("import StretchIO::*;")
    lines.append("import StretchCore::*;")
    lines.append("")
    lines.append("(* synthesize *)")
    lines.append(f"module mk{module_name}(Empty);")
    lines.append("  StretchCore core <- mkStretchCore;")
    lines.append("  Reg#(Bit#(32)) phase <- mkReg(0);")
    lines.append("  Reg#(Bit#(32)) stepCount <- mkReg(0);")
    lines.append("  Reg#(Bool)     halted <- mkReg(False);")
    lines.append("  Reg#(Bit#(32)) fails <- mkReg(0);")
    lines.append("")
    lines.append("  function Action check(String label, Word64 got, Word64 expected) =")
    lines.append("    action")
    lines.append("      if (got == expected)")
    lines.append('        $display("PASS %s = %0d (0x%0x)", label, got, got);')
    lines.append("      else begin")
    lines.append('        $display("FAIL %s = %0d (0x%0x), expected %0d (0x%0x)", label, got, got, expected, expected);')
    lines.append("        fails <= fails + 1;")
    lines.append("      end")
    lines.append("    endaction;")
    lines.append("")

    n_load = len(words)
    lines.append(f"  rule load (phase < {n_load} && core.mem.writeReady());")
    lines.append("    case (phase)")
    for i, (addr, val) in enumerate(words):
        lines.append(f"      {i}: core.mem.writeWord({addr}, 64'h{val:016x});")
    lines.append("    endcase")
    lines.append("    phase <= phase + 1;")
    lines.append("  endrule")
    lines.append("")

    n_reader = len(reader_image)
    reader_load_phase = n_load
    if n_reader:
        lines.append(f"  rule loadReader (phase >= {reader_load_phase} && phase < {reader_load_phase + n_reader});")
        lines.append(f"    case (phase - {reader_load_phase})")
        for i, val in enumerate(reader_image):
            lines.append(f"      {i}: core.io.loadReaderWord({i}, 64'h{val & ((1<<64)-1):016x});")
        lines.append("    endcase")
        lines.append("    phase <= phase + 1;")
        lines.append("  endrule")
        lines.append("")

    n_tape = len(tape_image)
    tape_load_phase = reader_load_phase + n_reader
    if n_tape:
        lines.append(f"  rule loadTape (phase >= {tape_load_phase} && phase < {tape_load_phase + n_tape});")
        lines.append(f"    case (phase - {tape_load_phase})")
        for i, val in enumerate(tape_image):
            lines.append(f"      {i}: core.io.writeTapeWord({i}, 64'h{val & ((1<<64)-1):016x});")
        lines.append("    endcase")
        lines.append("    phase <= phase + 1;")
        lines.append("  endrule")
        lines.append("")

    run_phase = tape_load_phase + n_tape
    lines.append(f"  rule setStart (phase == {run_phase});")
    lines.append(f"    core.setPC({prog.end_pc});")
    lines.append(f"    phase <= {run_phase + 1};")
    lines.append("  endrule")
    lines.append("")

    run_phase += 1
    lines.append(f"  rule run (phase == {run_phase} && !halted && stepCount < {step_cap});")
    lines.append("    let h <- core.step();")
    lines.append("    halted <= h;")
    lines.append("    stepCount <= stepCount + 1;")
    lines.append("  endrule")
    lines.append("")
    lines.append(f"  rule afterRun (phase == {run_phase} && (halted || stepCount == {step_cap}));")
    lines.append(f"    if (!halted) begin")
    lines.append(f"      $display(\"FAIL: step cap ({step_cap}) reached without halting -- checks below run against mid-execution state\");")
    lines.append(f"      fails <= fails + 1;")
    lines.append(f"    end")
    lines.append(f"    phase <= {run_phase + 1};")
    lines.append("  endrule")
    lines.append("")

    # Each check is two phases: issue the read, then collect it once
    # core.mem.responseReady() says the memory units have answered
    # (variable latency -- docs/microarchitecture_plan.md stage 1).
    # The loader likewise waits for writeReady(), since stores queue
    # behind busy memory units.
    check_phase0 = run_phase + 1
    for i, (label, addr_expr, expected) in enumerate(checks):
        req_phase = check_phase0 + 2 * i
        resp_phase = req_phase + 1
        lines.append(f"  rule checkReq{i} (phase == {req_phase});")
        lines.append(f"    core.mem.readWordReq({addr_expr});")
        lines.append(f"    phase <= {resp_phase};")
        lines.append("  endrule")
        lines.append("")
        lines.append(f"  rule checkResp{i} (phase == {resp_phase} && core.mem.responseReady());")
        lines.append(f"    let v{i} <- core.mem.readWordResp();")
        lines.append(f'    check("{label}", v{i}, 64\'h{expected & ((1<<64)-1):016x});')
        lines.append(f"    phase <= {resp_phase + 1};")
        lines.append("  endrule")
        lines.append("")

    pcheck_phase0 = check_phase0 + 2 * len(checks)
    for i, (label, dev_idx, expected) in enumerate(printer_checks):
        lines.append(f"  rule pcheck{i} (phase == {pcheck_phase0 + i});")
        lines.append(f'    check("{label}", core.io.readPrinterWord({dev_idx}), 64\'h{expected & ((1<<64)-1):016x});')
        lines.append(f"    phase <= {pcheck_phase0 + i + 1};")
        lines.append("  endrule")
        lines.append("")

    tcheck_phase0 = pcheck_phase0 + len(printer_checks)
    for i, (label, tape_idx, expected) in enumerate(tape_checks):
        lines.append(f"  rule tcheck{i} (phase == {tcheck_phase0 + i});")
        lines.append(f'    check("{label}", core.io.readTapeWord({tape_idx}), 64\'h{expected & ((1<<64)-1):016x});')
        lines.append(f"    phase <= {tcheck_phase0 + i + 1};")
        lines.append("  endrule")
        lines.append("")

    # Final instruction-counter check ("PC=EXPECTED"): where the
    # program halted. A branch to itself halts this model (StretchCore
    # step() returns True when next == pc), which is exactly the I-Box
    # diagnostics' own "BD,$" hang-on-failure idiom -- so a verbatim
    # diagnostic block can be run with its own pass/fail mechanism
    # intact: pass = halted at the block's end, fail = halted at the
    # offending hang, distinguishable by PC alone.
    pccheck_phase = tcheck_phase0 + len(tape_checks)
    # Cycle bound ("CYCLES<=N"): the run rule fires once per clock, so
    # stepCount at halt is the program's cycle count on this model --
    # today one step() per (half of an) instruction, later the cycle
    # count of the microarchitecture model (docs/microarchitecture_
    # plan.md stage 0). A separate check from the architectural ones
    # so a timing regression never masquerades as a wrong result.
    if cycle_bound is not None:
        lines.append(f"  rule cyclecheck (phase == {pccheck_phase});")
        lines.append(f"    if (stepCount <= {cycle_bound})")
        lines.append(f'      $display("PASS cycles = %0d (bound {cycle_bound})", stepCount);')
        lines.append("    else begin")
        lines.append(f'      $display("FAIL cycles = %0d, bound {cycle_bound}", stepCount);')
        lines.append("      fails <= fails + 1;")
        lines.append("    end")
        lines.append(f"    phase <= {pccheck_phase + 1};")
        lines.append("  endrule")
        lines.append("")
        pccheck_phase += 1
    if pc_check is not None:
        lines.append(f"  rule pccheck (phase == {pccheck_phase});")
        lines.append(f'    check("PC (half-word address)", zeroExtend(core.getPC()), {pc_check});')
        lines.append(f"    phase <= {pccheck_phase + 1};")
        lines.append("  endrule")
        lines.append("")
        pccheck_phase += 1

    finish_phase = pccheck_phase
    lines.append(f"  rule finish (phase == {finish_phase});")
    lines.append("    if (fails == 0)")
    lines.append('      $display("ALL TESTS PASSED");')
    lines.append("    else")
    lines.append('      $display("%0d TEST(S) FAILED", fails);')
    lines.append("    $finish(0);")
    lines.append("  endrule")
    lines.append("")
    lines.append("endmodule")
    lines.append("")
    lines.append("endpackage")
    return "\n".join(lines) + "\n"


if __name__ == '__main__':
    # Simple CLI: gen_tb.py program.strap ModuleName [ARG ...], where ARG is
    # one of:
    #   LABEL:ADDR=EXPECTED    -- a core-storage check (as before)
    #   P:LABEL:INDEX=EXPECTED -- a simulated-printer-word check (INDEX is a
    #                             plain device index 0..DeviceWords-1, not a
    #                             STRAP expression, since the printer has no
    #                             addressing of its own -- see StretchIO.bsv)
    #   R=W0,W1,W2,...         -- pre-load the simulated card reader's image
    #                             with these words, in order, index 0 first
    #                             (int(x,0), so hex "0x..." or decimal both
    #                             work); at most one R= argument is allowed
    #   T=W0,W1,W2,...         -- pre-load the simulated tape's image, same
    #                             syntax as R=; at most one T= argument
    #   CYCLES<=N              -- check that the run halted within N clock
    #                             cycles (stepCount); the timing oracle,
    #                             kept separate from the result checks
    #   PC=EXPECTED            -- check the instruction counter (a 19-bit
    #                             half-word address) where the program
    #                             halted; see the pccheck rule above
    #   TC:LABEL:INDEX=EXPECTED -- a simulated-tape-word check (INDEX is a
    #                             plain tape index 0..TapeWords-1), for
    #                             verifying what a W instruction wrote to
    #                             tape -- see StretchIO.bsv
    if len(sys.argv) < 3:
        print(f"usage: {sys.argv[0]} program.strap ModuleName "
              f"[LABEL:ADDR=EXPECTED | P:LABEL:INDEX=EXPECTED | "
              f"TC:LABEL:INDEX=EXPECTED | R=W0,W1,... | T=W0,W1,... ...]",
              file=sys.stderr)
        sys.exit(1)
    with open(sys.argv[1]) as f:
        src = f.read()
    try:
        prog = assemble(src)
    except AssemblerError as e:
        print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    module_name = sys.argv[2]
    checks = []
    printer_checks = []
    tape_checks = []
    reader_image = None
    tape_image = None
    pc_check = None
    cycle_bound = None
    for spec in sys.argv[3:]:
        if spec.startswith('PC='):
            pc_check = int(spec[3:], 0)
        elif spec.startswith('CYCLES<='):
            cycle_bound = int(spec[8:], 0)
        elif spec.startswith('R='):
            reader_image = [int(x, 0) for x in spec[2:].split(',') if x]
        elif spec.startswith('T='):
            tape_image = [int(x, 0) for x in spec[2:].split(',') if x]
        elif spec.startswith('P:'):
            label, rest = spec[2:].split(':', 1)
            idx_expr, expected = rest.split('=', 1)
            printer_checks.append((label, int(idx_expr, 0), int(expected, 0)))
        elif spec.startswith('TC:'):
            label, rest = spec[3:].split(':', 1)
            idx_expr, expected = rest.split('=', 1)
            tape_checks.append((label, int(idx_expr, 0), int(expected, 0)))
        else:
            label, rest = spec.split(':', 1)
            addr_expr, expected = rest.split('=', 1)
            checks.append((label, addr_expr, int(expected, 0)))
    print(generate(module_name, prog, checks, reader_image=reader_image,
                    printer_checks=printer_checks, tape_image=tape_image,
                    tape_checks=tape_checks, pc_check=pc_check,
                    cycle_bound=cycle_bound))
